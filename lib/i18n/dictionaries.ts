export const DICTIONARIES: Record<Locale, Dictionary> = { en, tr, ru };

/** Replaces {placeholders} in a dictionary string. */
export function fmt(
  template: string,
  vars: Record<string, string | number> = {},
): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    String(vars[key] ?? ""),
  );
}

/** CLDR-ish plural category (ru needs one/few/many; en/tr just one/many). */
export function pluralForm(locale: Locale, n: number): "one" | "few" | "many" {
  if (locale === "ru") {
    const mod10 = n % 10;
    const mod100 = n % 100;
    if (mod10 === 1 && mod100 !== 11) return "one";
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return "few";
    return "many";
  }
  return n === 1 ? "one" : "many";
}
